def pick(lst):
    return random.choice(lst)

dialogs = []
idx = 1

def add(turns, topic, memory_checks=None):
    global idx
    assert len(turns) % 2 == 0
    assert turns[0][0] == "user"
    assert turns[-1][0] == "bot"
    d = {
        "id": f"ru-{idx:04d}",
        "lang": "ru",
        "topic": topic,
        "turns": [{"role": r, "text": t} for r, t in turns],
    }
    if memory_checks:
        d["memory_checks"] = memory_checks
    dialogs.append(d)
    idx += 1

