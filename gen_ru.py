def math_dialog():
    a, b = random.randint(2, 50), random.randint(2, 20)
    op = pick(["+","-","*"])
    if op == "+":
        res = a + b; opw = "плюс"
    elif op == "-":
        if a < b: a, b = b, a
        res = a - b; opw = "минус"
    else:
        a, b = random.randint(2,12), random.randint(2,12)
        res = a * b; opw = "умножить на"
    turns = [
        ("user", f"Сколько будет {a} {opw} {b}?"),
        ("bot", f"{a} {opw} {b} = {res}."),
    ]
    c = random.randint(2, 10)
    res2 = res + c
    turns += [("user", f"А если ещё {c} добавить?"), ("bot", f"{res} плюс {c} = {res2}.")]
    turns += [("user", "Спасибо, понял."), ("bot", "Пожалуйста, обращайся, если будут ещё примеры.")]
    add(turns, "math")

