def greet_small_talk():
    n = pick(names)
    openers = [
        [("user", f"Привет!"), ("bot", "Привет! Как дела?")],
        [("user", "Хай, как сам?"), ("bot", "Привет! Всё норм, а у тебя?")],
        [("user", "Доброе утро"), ("bot", "Доброе! Как спалось?")],
    ]
    o = pick(openers)
    turns = list(o[0]) and o
