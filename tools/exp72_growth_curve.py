def score(A, label=None):
    ok = wrong = none_ok = sem = 0; details = []
    taught_rels = {w for s in STREAM for w in re.findall(r"[а-яё]+", s.lower()) }
    for t, g in TEST:
        r = A.solve(t); a = (str(r["answer"]) if r else None)
        if g == "NONE": hit = a is None; none_ok += hit; wrong += (a is not None)
        else:
            from mini_ai.analogy import same
            hit = a is not None and (g.lower() in a.lower() or a.lower() in g.lower() or same(a.split(",")[0], g.split(",")[0]) or (re.fullmatch(r"-?[\d.]+", g) and re.search(r"-?[\d.]+", a or "") and abs(float(re.search(r"-?[\d.]+", a).group()) - float(g)) < 0.02))
            ok += bool(hit); wrong += (a is not None and not hit)
            if hit:
                rels = {x[1].split()[-1] for c, _ in A.clauses(t.rsplit(". ", 1)[0]) for x in A.triples(c)}
                if rels and not (rels & taught_rels): sem += 1
        details.append((t[:50], a, g, bool(hit)))
    return dict(ok=ok, wrong=wrong, none_ok=none_ok, sem=sem, details=details)

def copy_control(k):
    """ответ = ответ ближайшего по словам примера учителя из первых k реплик (у примеров ответ = последняя сущность/число вывода)"""
    ex = []
    for s in STREAM[:k]:
        m = re.search(r"(?:значит|поэтому)\s+(.+)$", s)
        if m: ex.append((set(re.findall(r"[а-яё]+", s.lower())), m.group(1)))
    ok = 0
    for t, g in TEST:
        if g == "NONE" or not ex: continue
        w = set(re.findall(r"[а-яё]+", t.lower())); best = max(ex, key=lambda e: len(e[0] & w) / len(e[0] | w))
        ans = best[1]
        if g.lower() in ans.lower() or (re.fullmatch(r"-?[\d.]+", g) and g in ans): ok += 1
    return ok

