"""exp67 — понимает ли она объяснение учителя. Протокол: объяснил ОДИН раз → пересказ → применение к новым задачам (другие слова, та же структура).
Контроль: те же задачи БЕЗ объяснения (должна не решить или решить хуже)."""
import sys; sys.path.insert(0, ".")
from mini_ai.understand import Understand

def run(U, tasks, label):
    ok = 0
    for t, gold in tasks:
        r = U.apply(t); a = (str(r["answer"]) if r else None)
        hit = a is not None and (gold.lower() in a.lower() or a.lower() in gold.lower())
        ok += hit; print(f"  {'✓' if hit else '✗'} {t[:70]} → {a}  (эталон {gold})")
    print(f"[{label}] {ok}/{len(tasks)}"); return ok

AGE = [("Диёр на 2 года старше Сардора, Сардор на 4 старше Камрона. Кто самый старший?", "Диёр"),
       ("Нигора младше Лолы на 1 год, Лола младше Азизы на 3. Кто старше: Нигора или Азиза, и на сколько?", "Азиза"),
       ("Тимур старше Жасура на 5, Жасур старше Бобура на 1, Бобур старше Акмаля на 2. Кто самый младший?", "Акмаль"),
       ("Малика выше Севары на 3 см, Севара выше Дианы на 2. Кто самая высокая?", "Малика"),
       ("Отабек бежит быстрее Санжара, Санжар быстрее Руслана. Кто быстрее: Руслан или Отабек?", "Отабек"),
       ("Самса дороже лепёшки на 2000, лепёшка дороже чая на 1000. На сколько самса дороже чая?", "3000")]
LOC = [("Риштан в Ферганской области, Ферганская область в Узбекистане, Узбекистан в Азии. Где находится Риштан, если по-крупному?", "Азия"),
       ("Шахрисабз в Кашкадарьинской области, область в Узбекистане. Где Шахрисабз?", "Узбекистан"),
       ("Кокаид входит в Сурхандарьинскую область, Сурхандарьинская область входит в Узбекистан. Где Кокаид?", "Узбекистан")]
FORM = [("Велик едет 15 км/ч, до парка 6 км. Сколько ехать?", "0.4"),
        ("Автобус идёт 60 км/ч, до Коканда 90 км. Сколько времени займёт?", "1.5"),
        ("У меня было 250000 сум, потратил 40000. Сколько осталось?", "210000"),
        ("Было 1000, купил ручку за 456. Сколько у меня осталось?", "544")]

if __name__ == "__main__":
    print("=== БЕЗ объяснения (контроль) ===")
    U0 = Understand(None, None); c = run(U0, AGE, "возраст") + run(U0, LOC, "место") + run(U0, FORM, "формулы")

    print("\n=== УЧИТЕЛЬ объясняет по одному разу ===")
    U = Understand(None, None)
    for expl in ["если X старше Y, а Y старше Z, то X старше Z", "старше — значит родился раньше", "если X в Y и Y в Z, то X в Z",
                 "время = путь / скорость", "остаток = было − потратил", "выше — транзитивно", "быстрее переносится по цепочке", "если X дороже Y и Y дороже Z, то X дороже Z"]:
        r, retell = U.explain(expl); print(f"  учитель: «{expl}»\n  она:     {retell}")
    print("\n=== ПРИМЕНЕНИЕ к новым задачам ===")
    t = run(U, AGE, "возраст") + run(U, LOC, "место") + run(U, FORM, "формулы")
    print(f"\nИТОГ: без объяснения {c}/{len(AGE)+len(LOC)+len(FORM)} → после 8 объяснений {t}/{len(AGE)+len(LOC)+len(FORM)}   | {U.report()}")
    r = U.apply(AGE[1][0]); print("\nПример вслух:", U.say_steps(r) if r else None)
