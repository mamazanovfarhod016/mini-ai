"""exp71 — речь той же материей. Учитель (я) даёт N реплика→ответ. Проверка на ПЕРЕФРАЗАХ (другие слова, тот же смысл) —
должна дать ответ того же случая; на чужих репликах (о другом) — должна честно сказать «нет случая». Число = верных переносов
из 12 и ложных ответов из 6. Сравниваем со старым слоем речи (converse: 15k случаев из датасетов) на тех же перефразах."""
import sys, os; sys.path.insert(0, ".")
from mini_ai.analogy import Speech
from tools.exp69_one_substance import meaning

TEACH = [("как ты сам?", "Нормально, учусь. А ты как?"), ("как дела?", "Хорошо, разбираю новые примеры. У тебя?"),
         ("что умеешь?", "Понимать примеры и переносить их на новое. Покажи задачу."),
         ("ты меня понимаешь?", "Не всегда. Если что-то не так — скажи, как ответить, я запомню."),
         ("кто тебя сделал?", "Фарход. Я учусь из разговора, без датасетов."), ("ты тупая", "Пока да, кое-где. Скажи, где ошиблась — исправлюсь."),
         ("спасибо", "Пожалуйста."), ("пока", "Пока. Возвращайся с задачами."), ("меня зовут Фарход", "Приятно, Фарход. Запомнила."),
         ("молодец", "Спасибо. Что дальше?")]
PARA = [("ну как ты?", 0), ("как сам?", 0), ("как жизнь?", 1), ("дела как?", 1), ("что ты можешь?", 2), ("какие у тебя умения?", 2),
        ("ты понимаешь меня?", 3), ("ты вообще меня понимаешь?", 3), ("кто твой создатель?", 4), ("кто тебя создал?", 4),
        ("ты глупая", 5), ("благодарю", 6)]
OTHER = ["сколько стоит айфон 15", "расскажи про Ферганскую долину", "что такое фотосинтез", "напиши код сортировки", "какая погода в Ташкенте", "переведи слово apple"]

def run(S, label):
    ok = 0; false = 0
    for q, idx in PARA:
        r = S.reply(q); hit = r and r["text"] and r["near"] == TEACH[idx][0]; ok += bool(hit)
        print(f"  {'✓' if hit else '✗'} «{q}» → {r and (r['text'] or r['how'])}  [ближайшее: {r and r['near']}]")
    for q in OTHER:
        r = S.reply(q); f = r and r["text"] is not None; false += bool(f)
        print(f"  {'✗ ЛОЖНО' if f else '✓ молчит'} «{q}» → {r and (r['text'] or r['how'])}")
    print(f"[{label}] перефразы {ok}/{len(PARA)} · ложных ответов {false}/{len(OTHER)}"); return ok, false

if __name__ == "__main__":
    print("=== без базы смысла (только общие слова) ===")
    S0 = Speech(None, None)
    for i, o in TEACH: S0.teach(i, o)
    a0 = run(S0, "words-only")
    print("\n=== со смыслом слов (meaning_ru) ===")
    M = meaning(); S1 = Speech(None, M)
    for i, o in TEACH: S1.teach(i, o)
    a1 = run(S1, "meaning")
    print("\n=== + 4 связи слов от учителя («благодарю — как спасибо») ===")
    for a, b in [("благодарю", "спасибо"), ("глупая", "тупая"), ("создатель", "сделал"), ("жизнь", "дела")]: print("  ", S1.link(a, b))
    a2 = run(S1, "meaning+links")
    print("\n=== старый слой речи (converse, 15k случаев из датасетов) на тех же перефразах ===")
    try:
        from mini_ai.converse import Converse
        class _m: russian = None
        C = Converse(_m(), os.path.expanduser("~/Developer/mini-ai-runs/memory-core/experimental_state"))
        for q, idx in PARA[:6]:
            r = C.respond(q); print(f"  «{q}» → {r and r['text'][:70]}  [{r and r['how']}]")
    except Exception as e: print("  converse недоступен:", e)
    print(f"\nEXP71: перефразы words-only {a0[0]}/12 (ложных {a0[1]}/6) · meaning {a1[0]}/12 (ложных {a1[1]}/6) · +4 связи слов {a2[0]}/12 (ложных {a2[1]}/6) · обучено 10 реплик")
