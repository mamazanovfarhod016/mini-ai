"""exp70 — ИСПРАВЛЕНИЕ как тот же механизм (вопрос Фархода «но дальше исправиться?»). Меряем: сколько исправлений, чтобы
класс ошибки ушёл (цель — ОДНО), и не ломает ли исправление то, что работало (15 held-out до/после).
Найденная настоящая ошибка (не придуманная): «Было 1000, потратил 300, потом потратил 200. Сколько осталось?» → 700
(случай «было − потратил» взял одну трату). Учитель исправляет один раз: «нет, 500, потому что было 1000, потратил 300 и 200 —
значит осталось 500». Проверка на НОВОЙ задаче того же класса с другими числами + старые 15."""
import sys, re; sys.path.insert(0, ".")
from mini_ai.analogy import Analogy
from tools.exp69_one_substance import EX, T, run, meaning

ERR = [("Было 1000 сум, потратил 300, потом потратил 200. Сколько осталось?", "500"),
       ("У меня было 50000 сум, потратила 12000, потом ещё 8000. Сколько осталось?", "30000"),
       ("Было 700, отдал 100, потом отдал 250. Сколько у меня осталось?", "350")]
A = Analogy(None, None, meaning())
for e in EX: A.tell(e)
base = run(A, "15 held-out до исправления")
def show(label):
    w = 0
    for t, g in ERR:
        r = A.solve(t); a = r and str(r["answer"]); ok = a == g; w += (a is not None and not ok); print(f"  {'✓' if ok else '✗'} {t} → {a}  (эталон {g})")
    print(f"  [{label}] неверных {w}/3"); return w
print("\n=== класс ошибки: две траты ==="); w0 = show("до")
r = A.solve(ERR[0][0])
print("\n=== ОДНО исправление учителя ===\n  учитель: «нет, 500, потому что было 1000, потратил 300 и 200 — значит осталось 500»")
print("  она:    ", A.correct(ERR[0][0], r, "нет, 500, потому что было 1000 сум, потратил 300 и потратил 200 — значит осталось 500 сум"))
w1 = show("после 1 исправления")
after = run(A, "15 held-out после исправления")
print(f"\nEXP70: неверных {w0}/3 → {w1}/3 после ОДНОГО исправления (две новые задачи с другими числами) · held-out {base}/15 → {after}/15 · {A.report()}")
