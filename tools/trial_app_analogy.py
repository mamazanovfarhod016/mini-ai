 ("Бахтиёр тяжелее Улугбека на 7 кг, Улугбек тяжелее Фируза на 3 кг. Кто самый тяжёлый?", "Бахтиёр"),
 ("Аня умнее Бена на 10 баллов, Бен умнее Яны на 5 баллов. На сколько Аня умнее Яны?", "на 15"),
