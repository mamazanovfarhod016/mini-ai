"""
Превращаем текст в вектор чисел (то, что нейросеть может «съесть»).

Идея: нейросеть не понимает буквы, она понимает только числа.
Поэтому каждую фразу мы превращаем в «мешок признаков»:

  1) слова целиком:           "как дила"  ->  w:как, w:дила
     + начало длинных слов:   "спасибки"  ->  p:спас
  2) символьные триграммы:    " как "     ->  " ка", "как", "ак "
                              " дила "    ->  " ди", "дил", "ила", "ла "

Триграммы — это секрет устойчивости к опечаткам: в «как дила» и «как дела»
большая часть кусочков совпадает (" ка", "как", "ак ", "ла "), поэтому
сеть видит почти одинаковые векторы и даёт одинаковый ответ.

Hashing trick: вместо огромного словаря «признак → номер» мы считаем
хеш-функцию FNV-1a от строки признака и берём остаток от деления на DIM.
Так вход сети всегда фиксированной длины (DIM), а словарь хранить не нужно —
модель получается маленькой. Иногда два признака попадают в одну ячейку
(коллизия), но сеть к этому привыкает.

ВАЖНО: ровно та же логика повторена в app/www/brain.js (JavaScript).
Если меняешь что-то здесь — поменяй и там (тест tests/test_parity.py это проверит).
"""
import math
import re

# Все виды апострофов в узбекской латинице (o', g', yo'q) просто убираем,
# чтобы "yo'q", "yoʻq" и "yoq" стали одним и тем же словом.
_APOSTROPHES = "'`’‘ʻʼ´"
_NON_LETTERS = re.compile(r"[^a-z0-9а-я]+")


def normalize(text: str) -> str:
    """Нижний регистр, ё→е, без апострофов и знаков препинания."""
    t = text.lower().replace("ё", "е")
    for a in _APOSTROPHES:
        t = t.replace(a, "")
    t = _NON_LETTERS.sub(" ", t)
    return " ".join(t.split())


def tokens(text: str) -> list[str]:
    """Список признаков-строк (слова + символьные триграммы)."""
    words = normalize(text).split()
    feats = []
    for w in words:
        feats.append("w:" + w)
        if len(w) > 4:
            # «основа» слова: тупой/тупая/тупые → p:туп… помогает с окончаниями
            feats.append("p:" + w[:4])
        padded = " " + w + " "
        for i in range(len(padded) - 2):
            feats.append("c:" + padded[i:i + 3])
    return feats


def fnv1a(s: str) -> int:
    """32-битный хеш FNV-1a по кодам символов (в JS — charCodeAt)."""
    h = 2166136261
    for ch in s:
        h ^= ord(ch)
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def is_latin(text: str) -> bool:
    """Фраза латиницей → отвечаем по-узбекски, кириллицей → по-русски."""
    t = normalize(text)
    lat = sum(1 for ch in t if "a" <= ch <= "z")
    cyr = sum(1 for ch in t if "а" <= ch <= "я")
    return lat > cyr


def vectorize(text: str, dim: int) -> list[float]:
    """
    Мешок признаков -> вектор длины dim.
    x[hash(признак) % dim] += 1, потом делим на длину вектора
    (L2-нормализация), чтобы длинные и короткие фразы были в одном масштабе.
    """
    x = [0.0] * dim
    for f in tokens(text):
        x[fnv1a(f) % dim] += 1.0
    norm = math.sqrt(sum(v * v for v in x))
    if norm > 0:
        x = [v / norm for v in x]
    return x
